import React, { useMemo, useState } from "react";
import {
  AlertTriangle,
  BellRing,
  Check,
  CheckCheck,
  CircleCheck,
  Clock3,
  Search,
  ShieldAlert,
} from "lucide-react";
import FraudAlertNotice from "../components/FraudAlertNotice.jsx";
import PageHeader from "../components/PageHeader.jsx";
import Panel from "../components/Panel.jsx";
import StatCard from "../components/StatCard.jsx";
import {
  getAlertRiskLevel,
  HIGH_RISK_THRESHOLD,
  MEDIUM_RISK_THRESHOLD,
} from "../utils/alertConfig.js";
import {
  ALERT_STATUS_STORAGE_KEY,
  countUnresolvedHighRiskAlerts,
  loadDemoAlertState,
} from "../utils/demoAlerts.js";
import { formatCurrency } from "../utils/formatters.js";

const timestampFormat = new Intl.DateTimeFormat("en-US", {
  dateStyle: "medium",
  timeStyle: "short",
});
const percent = (value) => `${(value * 100).toFixed(0)}%`;

function updateStatus(alerts, transactionId, status) {
  return alerts.map((alert) =>
    alert.transactionId === transactionId ? { ...alert, status } : alert,
  );
}

export default function Alerts() {
  const [alertState, setAlertState] = useState(loadDemoAlertState);
  const [search, setSearch] = useState("");
  const [riskFilter, setRiskFilter] = useState("");
  const [statusFilter, setStatusFilter] = useState("");
  const { alerts, persistenceWarning } = alertState;

  function changeStatus(transactionId, status) {
    setAlertState((current) => {
      const nextAlerts = updateStatus(current.alerts, transactionId, status);
      const statuses = Object.fromEntries(
        nextAlerts.map((alert) => [alert.transactionId, alert.status]),
      );

      try {
        window.sessionStorage.setItem(
          ALERT_STATUS_STORAGE_KEY,
          JSON.stringify(statuses),
        );
        return { alerts: nextAlerts, persistenceWarning: "" };
      } catch (error) {
        return {
          alerts: nextAlerts,
          persistenceWarning: `Could not save review statuses in this browser tab: ${error.message}. Changes will last only until you leave this page.`,
        };
      }
    });
  }

  const summary = useMemo(() => {
    const counts = alerts.reduce(
      (result, alert) => {
        result[getAlertRiskLevel(alert.fraudProbability)] += 1;
        if (alert.status === "Resolved") {
          result.resolved += 1;
        }
        return result;
      },
      { High: 0, Medium: 0, Low: 0, resolved: 0 },
    );
    return counts;
  }, [alerts]);

  const filteredAlerts = useMemo(() => {
    const query = search.trim().toLowerCase();
    return alerts.filter((alert) => {
      const risk = getAlertRiskLevel(alert.fraudProbability);
      const matchesSearch =
        !query ||
        alert.transactionId.toLowerCase().includes(query) ||
        alert.amount.toFixed(2).includes(query);
      return (
        matchesSearch &&
        (!riskFilter || risk === riskFilter) &&
        (!statusFilter || alert.status === statusFilter)
      );
    });
  }, [alerts, riskFilter, search, statusFilter]);

  const unresolvedHighRisk = countUnresolvedHighRiskAlerts(alerts);

  return (
    <>
      <PageHeader
        eyebrow="RISK OPERATIONS"
        title="Fraud alerts"
        description="Review sample risk alerts and track their status."
        action={
          <span className="alert-demo-tag">
            <BellRing size={14} />
            DEMO MODE
          </span>
        }
      />

      <div className="alert-demo-notice" role="note">
        <ShieldAlert size={17} />
        <p>
          <strong>Demo alert feed.</strong> These illustrative records are not
          generated by model predictions or stored by the API. Review and
          resolution statuses are kept only in this browser tab.
        </p>
      </div>

      {persistenceWarning && (
        <div className="alert-storage-warning" role="alert">
          {persistenceWarning}
        </div>
      )}

      <FraudAlertNotice count={unresolvedHighRisk} />

      <div className="stat-grid">
        <StatCard
          label="Total Alerts"
          value={alerts.length}
          detail="Illustrative demo records"
          icon={BellRing}
          tone="cyan"
        />
        <StatCard
          label="High-Risk Alerts"
          value={summary.High}
          detail={`Probability ≥ ${percent(HIGH_RISK_THRESHOLD)}`}
          icon={ShieldAlert}
          tone="red"
        />
        <StatCard
          label="Medium-Risk Alerts"
          value={summary.Medium}
          detail={`Probability ≥ ${percent(MEDIUM_RISK_THRESHOLD)}`}
          icon={AlertTriangle}
          tone="amber"
        />
        <StatCard
          label="Resolved Alerts"
          value={summary.resolved}
          detail="Resolved in this tab session"
          icon={CircleCheck}
          tone="green"
        />
      </div>

      <Panel
        title="Alert queue"
        subtitle={`${filteredAlerts.length} of ${alerts.length} sample alerts`}
        className="table-panel"
      >
        <div className="table-toolbar alert-toolbar">
          <label className="search-field">
            <Search size={17} />
            <input
              type="search"
              placeholder="Search transaction ID or amount"
              value={search}
              onChange={(event) => setSearch(event.target.value)}
              aria-label="Search alerts by transaction ID or amount"
            />
          </label>
          <select
            value={riskFilter}
            onChange={(event) => setRiskFilter(event.target.value)}
            aria-label="Filter alerts by risk level"
          >
            <option value="">All risk levels</option>
            <option value="High">High risk</option>
            <option value="Medium">Medium risk</option>
            <option value="Low">Low risk</option>
          </select>
          <select
            value={statusFilter}
            onChange={(event) => setStatusFilter(event.target.value)}
            aria-label="Filter alerts by status"
          >
            <option value="">All statuses</option>
            <option value="New">New</option>
            <option value="Reviewed">Reviewed</option>
            <option value="Resolved">Resolved</option>
          </select>
        </div>

        <div className="table-scroll">
          <table className="alerts-table">
            <thead>
              <tr>
                <th>Transaction ID</th>
                <th>Amount</th>
                <th>Fraud probability</th>
                <th>Risk level</th>
                <th>Timestamp</th>
                <th>Status</th>
                <th>Actions</th>
              </tr>
            </thead>
            <tbody>
              {filteredAlerts.map((alert) => {
                const risk = getAlertRiskLevel(alert.fraudProbability);
                return (
                  <tr key={alert.transactionId}>
                    <td className="mono-text">{alert.transactionId}</td>
                    <td>{formatCurrency(alert.amount)}</td>
                    <td>
                      <span className="alert-probability">
                        {percent(alert.fraudProbability)}
                      </span>
                    </td>
                    <td>
                      <span className={`risk-pill risk-${risk.toLowerCase()}`}>
                        {risk}
                      </span>
                    </td>
                    <td>{timestampFormat.format(new Date(alert.timestamp))}</td>
                    <td>
                      <span
                        className={`alert-status status-${alert.status.toLowerCase()}`}
                      >
                        {alert.status}
                      </span>
                    </td>
                    <td>
                      <div className="alert-actions">
                        {alert.status === "New" && (
                          <button
                            className="alert-action"
                            onClick={() =>
                              changeStatus(alert.transactionId, "Reviewed")
                            }
                            aria-label={`Mark ${alert.transactionId} as reviewed`}
                          >
                            <Check size={14} />
                            Review
                          </button>
                        )}
                        {alert.status !== "Resolved" && (
                          <button
                            className="alert-action alert-action-resolve"
                            onClick={() =>
                              changeStatus(alert.transactionId, "Resolved")
                            }
                            aria-label={`Mark ${alert.transactionId} as resolved`}
                          >
                            <CheckCheck size={14} />
                            Resolve
                          </button>
                        )}
                        {alert.status === "Resolved" && (
                          <span className="alert-complete">
                            <CircleCheck size={14} />
                            Complete
                          </span>
                        )}
                      </div>
                    </td>
                  </tr>
                );
              })}
              {filteredAlerts.length === 0 && (
                <tr>
                  <td className="empty-cell" colSpan={7}>
                    No sample alerts match these search and filter settings.
                  </td>
                </tr>
              )}
            </tbody>
          </table>
        </div>
        <div className="table-footer">
          <p>
            Demo-only feed. Status changes are saved in this browser tab, not
            sent to FastAPI, and reset when the tab is closed.
          </p>
          <span className="alert-threshold-note">
            <Clock3 size={13} />
            Risk bands use configured probability thresholds
          </span>
        </div>
      </Panel>
    </>
  );
}

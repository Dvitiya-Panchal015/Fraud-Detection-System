import React from "react";
import { AlertTriangle } from "lucide-react";

export default function FraudAlertNotice({ count, onClick }) {
  if (count === 0) {
    return null;
  }

  const message = `${count} potentially fraudulent transaction${
    count === 1 ? "" : "s"
  } require${count === 1 ? "s" : ""} attention.`;
  const content = (
    <>
      <AlertTriangle size={20} />
      <span className="fraud-alert-copy">
        <strong className="fraud-alert-title">Fraud Alert</strong>
        <span className="fraud-alert-message">{message}</span>
        <span className="fraud-alert-description">
          High-risk demo transactions are shown when their illustrative
          probability meets the configured threshold. These sample
          probabilities were not generated by live machine-learning scoring.
          Review the sample details and verify activity through your approved
          fraud investigation process.
        </span>
        <span className="fraud-alert-disclaimer">
          Demo alerts only — no real-time transactions are being monitored.
        </span>
      </span>
    </>
  );

  if (!onClick) {
    return <div className="alert-warning">{content}</div>;
  }

  return (
    <button
      type="button"
      className="alert-warning alert-warning-button"
      onClick={onClick}
      aria-live="polite"
      aria-label={`${message} Open Fraud Alerts`}
    >
      {content}
    </button>
  );
}
